"""Multi-label classification of mixed defect patterns (MixedWM38).

    python -m wafermap.mixed --data data/mixedwm38/Wafer_Map_Datasets.npz --out reports/mixed --seed 0

WM-811K gives each wafer one label, but a real wafer can carry several
patterns at once. MixedWM38 has 38,015 wafers of 52x52 dies with up to four
of eight patterns each (38 combinations). The CNN is the same as for
WM-811K, with eight independent sigmoid outputs instead of one softmax.

Things to know about the data:

- about 1,000 maps appear more than once; exact duplicates are removed
  before splitting, or copies would sit on both sides of the split;
- there is no lot information, so the split is random (stratified by
  combination), and most mixed wafers were generated by a GAN. Scores here
  are therefore not comparable with the lot-grouped WM-811K scores;
- a few cells hold the value 3, which the description does not explain;
  they are treated as failing dies.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import f1_score
from sklearn.model_selection import train_test_split
from torch import nn

from .cnn import WaferCNN, augment, one_hot, pick_device

LABELS = ["Center", "Donut", "Edge-Loc", "Edge-Ring", "Loc", "Near-full", "Scratch", "Random"]


def load_mixed(path: str | Path) -> tuple[np.ndarray, np.ndarray]:
    """Unique wafer maps (N, 52, 52) uint8 in {0, 1, 2} and their labels (N, 8) in {0, 1}."""
    data = np.load(path, allow_pickle=False)
    X = np.minimum(data["arr_0"], 2).astype(np.uint8)
    y = data["arr_1"].astype(np.uint8)
    _, first = np.unique(X.reshape(len(X), -1), axis=0, return_index=True)
    first.sort()
    return X[first], y[first]


def combo_names(y: np.ndarray) -> np.ndarray:
    """Readable name of each row's label combination, e.g. 'Center+Scratch' or 'none'."""
    return np.array(["+".join(l for l, on in zip(LABELS, row) if on) or "none" for row in y])


def split(y: np.ndarray, seed: int):
    """60/20/20 train/val/test indices, stratified by label combination."""
    combo = combo_names(y)
    idx = np.arange(len(y))
    fit, test = train_test_split(idx, test_size=0.2, stratify=combo, random_state=seed)
    train, val = train_test_split(fit, test_size=0.25, stratify=combo[fit], random_state=seed + 1)
    return train, val, test


def evaluate(y_true: np.ndarray, proba: np.ndarray, threshold: float = 0.5) -> dict:
    """Exact-match rate (all eight labels right), per-label F1 and exact match by pattern count."""
    pred = (proba >= threshold).astype(np.uint8)
    exact = (pred == y_true).all(1)
    n_patterns = y_true.sum(1)
    return {"exact_match": float(exact.mean()),
            "macro_f1": float(f1_score(y_true, pred, average="macro", zero_division=0)),
            "f1": dict(zip(LABELS, map(float, f1_score(y_true, pred, average=None, zero_division=0)))),
            "exact_by_patterns": {int(k): float(exact[n_patterns == k].mean()) for k in np.unique(n_patterns)}}


def combo_table(y_true: np.ndarray, proba: np.ndarray, threshold: float = 0.5) -> pd.DataFrame:
    """Exact-match rate per true combination, worst first, with its most common wrong prediction."""
    pred = (proba >= threshold).astype(np.uint8)
    frame = pd.DataFrame({"combo": combo_names(y_true), "pred": combo_names(pred)})
    frame["exact"] = frame["combo"] == frame["pred"]
    rows = []
    for combo, g in frame.groupby("combo"):
        wrong = g.loc[~g["exact"], "pred"]
        rows.append({"combo": combo, "wafers": len(g), "exact_match": g["exact"].mean(),
                     "most_common_error": wrong.mode().iloc[0] if len(wrong) else ""})
    return pd.DataFrame(rows).sort_values("exact_match").reset_index(drop=True)


@torch.no_grad()
def predict_proba(model: nn.Module, X: torch.Tensor, device: str, batch_size: int = 512) -> np.ndarray:
    model.eval()
    out = [torch.sigmoid(model(one_hot(X[i:i + batch_size].to(device)))).cpu() for i in range(0, len(X), batch_size)]
    return torch.cat(out).numpy()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", default="reports/mixed")
    ap.add_argument("--name", default="mixed")
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--batch-size", type=int, default=128)
    ap.add_argument("--lr", type=float, default=2e-3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-wafers", type=int, default=None)
    args = ap.parse_args()

    torch.manual_seed(args.seed)
    device = pick_device()
    X_np, y_np = load_mixed(args.data)
    if args.max_wafers and len(X_np) > args.max_wafers:
        keep = np.random.default_rng(args.seed).choice(len(X_np), args.max_wafers, replace=False)
        X_np, y_np = X_np[keep], y_np[keep]
    train, val, test = split(y_np, args.seed)
    X, y = torch.from_numpy(X_np), torch.from_numpy(y_np).float()
    print(f"device={device}  unique wafers={len(X)}  train={len(train)}  val={len(val)}  test={len(test)}", flush=True)

    model = WaferCNN(n_classes=len(LABELS)).to(device)
    loss_fn = nn.BCEWithLogitsLoss()
    opt = torch.optim.Adam(model.parameters(), lr=args.lr)
    schedule = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)
    train_t, X_val, X_test = torch.from_numpy(train), X[torch.from_numpy(val)], X[torch.from_numpy(test)]
    best, best_epoch, best_state = -1.0, 0, None
    for epoch in range(1, args.epochs + 1):
        model.train()
        total = 0.0
        for batch in train_t[torch.randperm(len(train_t))].split(args.batch_size):
            opt.zero_grad()
            loss = loss_fn(model(augment(one_hot(X[batch].to(device)))), y[batch].to(device))
            loss.backward()
            opt.step()
            total += loss.item() * len(batch)
        schedule.step()
        exact = evaluate(y_np[val], predict_proba(model, X_val, device))["exact_match"]
        if exact > best:
            best, best_epoch, best_state = exact, epoch, copy.deepcopy(model.state_dict())
        print(f"epoch {epoch:2d}  train loss {total / len(train_t):.4f}  val exact match {exact:.4f}", flush=True)

    model.load_state_dict(best_state)
    proba = predict_proba(model, X_test, device)
    result = {"name": args.name, "seed": args.seed, "best_epoch": best_epoch, "n_train": int(len(train)),
              "n_test": int(len(test)), **evaluate(y_np[test], proba)}
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{args.name}_mixed.json").write_text(json.dumps(result, indent=2))
    combo_table(y_np[test], proba).to_csv(out / f"{args.name}_combos.csv", index=False)
    torch.save(best_state, out / f"{args.name}.pt")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
